"""Obsidian integration (opt-in): engine-owned views under learner/, for a vault opened on learner/.

Git stays the only sync; Obsidian is an editor/viewer over the git-synced tree. This module
writes, when the learner has turned it on (`calamity obsidian`, profile key `obsidian`):

- `learner/Today.md` — the daily-goals dashboard (the finish line as checkboxes, the `Now:` block,
  due reviews, tasks, the next action). Machine-local and regenerated each session, so it is
  gitignored, never committed, never a source of truth.
- `learner/books/_Index.md` and `learner/books/<topic>/_MOC.md` — a track index and a per-book Map
  of Content linking the chapters in order (generated views, committed like the books themselves).
- stable YAML frontmatter on each chapter (`calamity: book-chapter`, track/skill/topic/chapter),
  added only to a chapter that has none, so the learner's own edits are never clobbered.

Progress still changes only through the engine; Obsidian never writes back. Live state
(mastery, review dates) is computed fresh into Today.md, never baked into chapter files.
"""
import os

from .store import read_text, write_text


def enabled(repo) -> bool:
    return bool(repo.prof("obsidian"))


# ---------------------------------------------------------------- the daily-goals dashboard


def _check(done: bool) -> str:
    return "- [x]" if done else "- [ ]"


def dashboard(repo, tree, state, when) -> str:
    """learner/Today.md as Markdown: the finish line as checkboxes, plus the Now block, due reviews,
    tasks and the next action. Plain Markdown so it needs no Obsidian plugin."""
    from . import plan, day as day_mod, tasks

    t = plan.today(repo, tree, state, when)
    n = t["n"]
    out = ["# Today — %s" % when.strftime("%A %Y-%m-%d"), ""]

    now = day_mod.now_lines(repo, when)
    if now:
        out += ["> " + now[0], ""]
        for extra in now[1:]:
            out += ["> " + extra, ""]

    out += ["## Finish line", ""]
    if n["reviews_needed"] or n["due_done"]:
        out.append("%s Reviews due: %d / %d" % (_check(t["reviews_left"] == 0), n["due_done"], n["reviews_needed"]))
    if t["relearn"]:
        out.append("- [ ] Re-learn (slipped back): %d" % t["relearn"])
    if t["new_target"]:
        out.append("%s New topics: %d / %d" % (_check(t["new_left"] == 0), n["new_done"], t["new_target"]))
    if n["consolidate_total"]:
        out.append("%s Consolidate: %d / %d" % (_check(t["consolidate_left"] == 0),
                                                n["consolidated"], n["consolidate_total"]))
    if t["lecture_target"]:
        out.append("%s Lectures: %d / %d" % (_check(t["lectures_left"] == 0),
                                             t["lectures_done"], t["lecture_target"]))
    if len(out) and out[-1] == "":
        pass
    out += ["", "_%s_" % plan.finish_text(t), ""]

    due = state.due(when)
    if due:
        out += ["## Due now (most forgotten first)", ""]
        for key, ts in due[:8]:
            out.append("- `%s` — recall %d%%" % (key, round(100 * state.retrievability(key, when))))
        out.append("")

    task_line = tasks.brief_line(repo, tree, state, when)
    if task_line:
        # "Tasks: a (…) · b · +1 more (tasks)" -> one checkbox per task
        body = task_line.split(":", 1)[1] if ":" in task_line else task_line
        items = [p.strip() for p in body.split("·") if p.strip()]
        if items:
            out += ["## Tasks", ""] + ["- [ ] %s" % it for it in items] + [""]

    action = plan.action_label(plan.next_action(repo, tree, state, when))
    out += ["## Next action", "", action, "",
            "---", "", "_Generated by Calamity — a view, regenerated each session. "
            "Progress changes only through the engine; do not edit this file._", ""]
    return "\n".join(out)


# ---------------------------------------------------------------- the books vault (MOC + index + frontmatter)


def _book_dirs(repo) -> list:
    base = os.path.join(repo.learner, "books")
    if not os.path.isdir(base):
        return []
    out = []
    for name in sorted(os.listdir(base)):
        path = os.path.join(base, name)
        if os.path.isdir(path) and _chapters(path):
            out.append((name, path))
    return out


def _chapters(path: str) -> list:
    """Chapter files of a book, in order: the NN-*.md files (README and engine views excluded)."""
    try:
        names = sorted(os.listdir(path))
    except OSError:
        return []
    return [n for n in names if n.endswith(".md") and n[:2].isdigit() and not n.startswith("_")]


def _title(path: str, fallback: str) -> str:
    """A book's title: the first heading of its README, else the folder name prettified."""
    readme = os.path.join(path, "README.md")
    if os.path.isfile(readme):
        for line in read_text(readme).splitlines():
            if line.startswith("# "):
                return line[2:].strip()
    return fallback.replace("-", " ").replace(".", " ").strip().title()


def _skill_track(tree, topic: str):
    node = tree.nodes.get(topic)
    if node is not None:
        return topic, getattr(node, "track", "") or ""
    skill = topic.split("/", 1)[0]
    node = tree.nodes.get(skill)
    return skill, (getattr(node, "track", "") if node is not None else "") or ""


def _chapter_label(path: str, name: str) -> str:
    for line in read_text(os.path.join(path, name)).splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return name[:-3].replace("-", " ")[3:].strip().title() or name[:-3]


def _ensure_frontmatter(repo, tree, path: str, topic: str):
    """Add stable frontmatter to each chapter that has none. Never rewrite a chapter that already
    starts with '---' (it may hold the learner's own edits)."""
    skill, track = _skill_track(tree, topic)
    for i, name in enumerate(_chapters(path), 1):
        fp = os.path.join(path, name)
        text = read_text(fp)
        if text.lstrip().startswith("---"):
            continue
        fm = ["---", "calamity: book-chapter"]
        if track:
            fm.append("track: %s" % track)
        fm += ["skill: %s" % skill, "topic: %s" % topic, "chapter: %d" % i, "---", ""]
        write_text(fp, "\n".join(fm) + text)


def _moc(repo, tree, topic: str, path: str) -> str:
    skill, track = _skill_track(tree, topic)
    head = ["---", "calamity: book-moc"]
    if track:
        head.append("track: %s" % track)
    head += ["skill: %s" % skill, "---", "", "# %s" % _title(path, topic), "",
             "Chapters, in order:", ""]
    links = ["- [[%s|%s]]" % (name[:-3], _chapter_label(path, name)) for name in _chapters(path)]
    return "\n".join(head + links) + "\n"


def _index(repo, tree, books: list) -> str:
    """learner/books/_Index.md: books grouped by track, then skill, each linking its MOC."""
    by_track = {}
    for topic, path in books:
        skill, track = _skill_track(tree, topic)
        by_track.setdefault(track or "other", []).append((skill, topic, path))
    out = ["---", "calamity: book-index", "---", "", "# Study books", ""]
    for track in sorted(by_track):
        out += ["## %s" % track, ""]
        for skill, topic, path in sorted(by_track[track]):
            out.append("- [[%s/_MOC|%s]]" % (topic, _title(path, topic)))
        out.append("")
    # Optional navigation table for the Dataview plugin. Without the plugin it shows as a labelled
    # code block; the wikilink lists above always work on their own.
    out += ["## All chapters (requires the Dataview plugin)", "",
            "```dataview", "TABLE skill AS Skill, chapter AS Chapter", 'FROM "books"',
            'WHERE calamity = "book-chapter"', "SORT skill ASC, chapter ASC", "```", ""]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- the whole render


def render(repo, tree, state, when) -> dict:
    """Write every Obsidian view. Returns {written: [paths]}; best-effort, raising nothing the
    caller must handle — a view that cannot be built is simply skipped."""
    written = []
    today = os.path.join(repo.learner, "Today.md")
    try:
        write_text(today, dashboard(repo, tree, state, when), durable=False)
        written.append(today)
    except Exception:  # noqa: BLE001 — a dashboard failure must never break the session
        pass
    books = _book_dirs(repo)
    for topic, path in books:
        try:
            _ensure_frontmatter(repo, tree, path, topic)
            moc = os.path.join(path, "_MOC.md")
            write_text(moc, _moc(repo, tree, topic, path))
            written.append(moc)
        except Exception:  # noqa: BLE001
            pass
    if books:
        try:
            index = os.path.join(repo.learner, "books", "_Index.md")
            write_text(index, _index(repo, tree, books))
            written.append(index)
        except Exception:  # noqa: BLE001
            pass
    return {"written": written}


def render_if_enabled(repo, tree, state, when) -> None:
    """For the session-start hook and the scheduler: render only when the learner has turned it on,
    and never raise."""
    try:
        if enabled(repo):
            render(repo, tree, state, when)
    except Exception:  # noqa: BLE001
        pass
